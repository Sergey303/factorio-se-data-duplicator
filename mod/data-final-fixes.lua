-- Space Exploration data-card copying (Factorio 2.1).
-- Intentional: prototype-only mod; no runtime event handlers are required.

local PREFIX = "se-data-duplicator-copy-"
local CATEGORY = "se-data-duplicator-copying"
local REQUIRED_MACHINES = {
  "se-space-supercomputer-1",
  "se-space-supercomputer-2",
  "se-space-supercomputer-3",
  "se-space-supercomputer-4"
}
local EMPTY = "se-empty-data"
local JUNK = "se-junk-data"
local COLD = "se-space-coolant-cold"  -- -100 C, distinct fluid prototype in SE
local HOT = "se-space-coolant-hot"    -- +25 C, named "hot" in the SE prototype

local function setting(name)
  return settings.startup[name].value
end

local function check(condition, message)
  if not condition then error("[SE Data Duplicator] " .. message, 0) end
end

local function require_item(name)
  check(data.raw.item and data.raw.item[name], "Missing SE item: " .. name)
end

require_item(EMPTY)
require_item(JUNK)
check(data.raw.fluid and data.raw.fluid[COLD], "Missing SE thermofluid: " .. COLD)
check(data.raw.fluid and data.raw.fluid[HOT], "Missing SE thermofluid: " .. HOT)
check(data.raw["assembling-machine"], "Missing assembling-machine prototypes")
for _, machine_name in ipairs(REQUIRED_MACHINES) do
  check(data.raw["assembling-machine"][machine_name], "Missing SE supercomputer: " .. machine_name)
end

local failure = setting("se-data-duplicator-failure-percent") / 100
local craft_time = setting("se-data-duplicator-craft-seconds")
local coolant = setting("se-data-duplicator-coolant-amount")
local include_probes = setting("se-data-duplicator-include-probes")

check(not (data.raw["recipe-category"] and data.raw["recipe-category"][CATEGORY]),
      "Recipe category already exists: " .. CATEGORY)
data:extend({{type = "recipe-category", name = CATEGORY}})

-- Special items coming from scripted launches, without a standard craft recipe.
-- The fallbacks are intentionally late, never early. Existing unlocks take priority.
local function fallback_technology(item_name)
  if item_name:find("belt%-probe") or item_name:find("asteroid%-probe") then
    return "se-space-catalogue-astronomic-4"
  end
  if item_name:find("star%-probe") then
    return "se-space-catalogue-energy-4"
  end
  if item_name:find("void%-probe") or item_name:find("interstellar%-probe") then
    return "se-deep-catalogue-1"
  end
  -- Some other SE cards are generated by mechanics rather than regular recipes.
  -- Use the latest catalogue rather than making new data available too early.
  return "se-deep-catalogue-4"
end

local function is_probe_data(item_name)
  return item_name:find("probe") ~= nil
end

local function is_data_card(item_name)
  return item_name:match("^se%-.+%-data$") ~= nil
      and item_name ~= EMPTY
      and item_name ~= JUNK
      and item_name ~= "se-broken-data"
end

-- Index production recipes and the technology unlocks for each recipe.
-- Build the index before extending data.raw.recipe with our new recipes.
local recipes = data.raw.recipe or {}
local produces = {}
local recipe_is_enabled = {}
for recipe_name, recipe in pairs(recipes) do
  if recipe.results then
    for _, product in pairs(recipe.results) do
      if product.type == "item" and product.name and is_data_card(product.name) then
        produces[product.name] = produces[product.name] or {}
        produces[product.name][recipe_name] = true
        if recipe.enabled ~= false then
          recipe_is_enabled[product.name] = true
        end
      end
    end
  end
end

local tech_unlocks = {}
for technology_name, technology in pairs(data.raw.technology or {}) do
  for _, effect in pairs(technology.effects or {}) do
    if effect.type == "unlock-recipe" and effect.recipe then
      tech_unlocks[effect.recipe] = tech_unlocks[effect.recipe] or {}
      tech_unlocks[effect.recipe][technology_name] = true
    end
  end
end

local cards = {}
for name, item in pairs(data.raw.item or {}) do
  if is_data_card(name) and (include_probes or not is_probe_data(name)) then
    table.insert(cards, name)
  end
end
table.sort(cards)
check(#cards > 0, "No SE data cards were discovered; check SE version")

-- Only these machines may craft copies. Recipe categories are per entity,
-- so additions cannot accidentally make recipes craftable elsewhere.
for _, machine_name in ipairs(REQUIRED_MACHINES) do
  local machine = data.raw["assembling-machine"][machine_name]
  machine.crafting_categories = machine.crafting_categories or {}
  local found = false
  for _, category in ipairs(machine.crafting_categories) do
    if category == CATEGORY then found = true; break end
  end
  if not found then table.insert(machine.crafting_categories, CATEGORY) end
end

local function deep_copy(value)
  if type(value) ~= "table" then return value end
  local result = {}
  for key, child in pairs(value) do
    result[deep_copy(key)] = deep_copy(child)
  end
  return result
end

local function get_results(item_name)
  local result = {{type = "fluid", name = HOT, amount = coolant, temperature = 25}}
  -- Complementary, non-overlapping ranges share one roll in Factorio 2.1.
  if failure < 1 then
    local normal = {type = "item", name = item_name, amount = 2}
    if failure > 0 then
      normal.shared_probability = {min = 0, max = 1 - failure}
    end
    table.insert(result, normal)
  end
  if failure > 0 then
    local junk = {type = "item", name = JUNK, amount = 2}
    if failure < 1 then
      junk.shared_probability = {min = 1 - failure, max = 1}
    end
    table.insert(result, junk)
  end
  return result
end

local to_add = {}
local linked, fallback_count = 0, 0
for _, item_name in ipairs(cards) do
  local item = data.raw.item[item_name]
  local copy_name = PREFIX .. item_name
  check(item.icon or (item.icons and #item.icons > 0), "Missing icon for: " .. item_name)
  check(not recipes[copy_name], "Duplicate recipe: " .. copy_name)

  local unlocks = {}
  for recipe_name in pairs(produces[item_name] or {}) do
    for tech_name in pairs(tech_unlocks[recipe_name] or {}) do
      unlocks[tech_name] = true
    end
  end
  local fallback = false
  if not next(unlocks) then
    local tech = recipe_is_enabled[item_name] and "se-space-supercomputer-1"
               or fallback_technology(item_name)
    unlocks[tech] = true
    fallback = true
  end

  -- Always demand one normal and one blank card; 10 units of -100 C coolant.
  -- Machine has input/output fluidboxes, and fluid always returns as +25 C.
  table.insert(to_add, {
    type = "recipe",
    name = copy_name,
    categories = {CATEGORY},
    enabled = false,
    energy_required = craft_time,
    ingredients = {
      {type = "item", name = item_name, amount = 1},
      {type = "item", name = EMPTY, amount = 1},
      {type = "fluid", name = COLD, amount = coolant, temperature = -100}
    },
    results = get_results(item_name),
    -- Explicit icon instead of main_product: at 100% failure the original item
    -- is deliberately absent from the results array.
    icon = item.icon,
    icon_size = item.icon and (item.icon_size or 64) or nil,
    icons = item.icons and deep_copy(item.icons) or nil,
    localised_name = {"se-data-duplicator.copy-name", item.localised_name or {"item-name." .. item_name}},
    localised_description = {"se-data-duplicator.copy-description", tostring(setting("se-data-duplicator-failure-percent"))},
    subgroup = item.subgroup,
    order = "z[duplicate]-" .. (item.order or item_name),
    allow_productivity = false,
    maximum_productivity = 0,
    allow_quality = false,
    can_set_quality = false,
    auto_recycle = false,
    hide_from_player_crafting = true,
    allow_as_intermediate = false,
    always_show_made_in = true
  })

  local connected = 0
  for tech_name in pairs(unlocks) do
    local technology = (data.raw.technology or {})[tech_name]
    if technology then
      technology.effects = technology.effects or {}
      local already_present = false
      for _, effect in ipairs(technology.effects) do
        if effect.type == "unlock-recipe" and effect.recipe == copy_name then
          already_present = true; break
        end
      end
      if not already_present then
        table.insert(technology.effects, {type = "unlock-recipe", recipe = copy_name})
      end
      connected = connected + 1
    end
  end
  check(connected > 0, "Could not unlock copy of " .. item_name .. "; missing technology")
  linked = linked + 1
  if fallback then fallback_count = fallback_count + 1 end
end

data:extend(to_add)
log(string.format("[SE Data Duplicator] Generated %d copying recipes (%d fallback unlocks), %d%% failure, %ds, %d coolant",
  linked, fallback_count, failure * 100, craft_time, coolant))
